    ]
    private static let obfuscated: [UInt8] = [
        251, 1, 41, 174, 211, 225, 213, 158, 177, 202, 38, 234, 71, 224, 148, 63, 153, 106, 152, 61, 158, 13, 83, 238, 66, 128, 189, 155, 82, 68, 141, 52, 101, 122, 4, 201, 70, 209, 160, 38, 181, 191, 199, 171, 94, 243, 71, 121, 22, 35, 102, 216, 211, 61, 184, 110, 208, 34, 56, 246, 65, 167, 176, 33, 128, 222, 109, 178, 92, 171, 67, 205, 86
